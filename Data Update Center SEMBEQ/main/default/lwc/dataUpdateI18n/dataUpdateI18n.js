export function format(template, ...args) {
    if (!template) return '';
    return template.replace(/\{(\d+)\}/g, (_, i) => (args[i] !== undefined ? args[i] : ''));
}

// Different Data_Update_Form__mdt records use different fields as their second identity
// field (e.g. AEBEQ_Account_Update → LastName, AEBEQ_Eglise_Update → the church's NEQ
// number) — the portal (dataUpdateForm) reads config.identityField2ApiName from the
// server and looks up the right label/placeholder pair here instead of a single
// hardcoded "last name" string, so adding a form with a third kind of identity field
// only needs a new entry below, not a template change.
const IDENTITY_FIELD_2_LABEL_KEYS = {
    LastName: { label: 'lastNameLabel', placeholder: 'lastNamePlaceholder' },
    Enregistrement_provincial_etatique__c: { label: 'neqLabel', placeholder: 'neqPlaceholder' }
};

export function getIdentity2Labels(lang, identityField2ApiName) {
    const labels = getLabels(lang);
    const keys = IDENTITY_FIELD_2_LABEL_KEYS[identityField2ApiName] || IDENTITY_FIELD_2_LABEL_KEYS.LastName;
    return { label: labels[keys.label], placeholder: labels[keys.placeholder] };
}
